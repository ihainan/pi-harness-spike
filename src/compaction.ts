// Minimal in-place compaction. Algorithm follows pi-coding-agent's idea, but its implementation
// could not be taken: prepareCompaction is not exported, compact() wants SessionEntry[], and the
// package root costs +72MB RSS / +470ms to import (measured). Steps: prune old tool results →
// if still over, summarize the old prefix with a fixed structure → keep a recent suffix that
// never starts inside a tool-call/tool-result pair. sessionId does not change.
import type { AgentMessage } from "@earendil-works/pi-agent-core";
import type { HarnessConfig } from "./model.js";

const PRUNED = "[old tool output pruned]";
const KEEP_RECENT_RATIO = 0.3;
const CLAMP_RESERVE = 4096 + 2048; // pi-ai's CONTEXT_SAFETY_TOKENS + room for a usable reply
const SUMMARY_PREFIX = "[Summary of the earlier conversation, generated by compaction]\n";

const SYSTEM = `You are a context summarization assistant. Read the conversation and output a structured summary. Preserve every concrete fact, identifier, file path, number and user instruction verbatim. Do not answer the conversation.`;
const TEMPLATE = `Summarize the conversation below using exactly these sections:
## Goal
## Constraints
## Progress
## Key Decisions
## Next Steps
## Critical Context (verbatim facts, values, identifiers, paths)

<conversation>
`;

export function estimateText(s: string): number {
	let cjk = 0;
	for (const ch of s) {
		const c = ch.codePointAt(0)!;
		if ((c >= 0x2e80 && c <= 0x9fff) || (c >= 0xac00 && c <= 0xd7af) || (c >= 0xf900 && c <= 0xfaff) || (c >= 0xff00 && c <= 0xffef)) cjk++;
	}
	const rest = s.length - cjk;
	return Math.ceil(cjk + rest / 4);
}

function messageText(m: any): string {
	if (typeof m.content === "string") return m.content;
	if (!Array.isArray(m.content)) return "";
	return m.content
		.map((b: any) => {
			if (b.type === "text") return b.text;
			if (b.type === "thinking") return b.thinking ?? "";
			if (b.type === "toolCall") return `${b.name} ${JSON.stringify(b.arguments)}`;
			return "";
		})
		.join("\n");
}

export function estimateMessage(m: AgentMessage): number {
	return estimateText(messageText(m)) + 8;
}

/**
 * Last real usage anchors the estimate; only messages after it are estimated. Same rule as
 * pi-ai's estimateContextTokens: a usage older than any message before it no longer describes
 * the prefix, because that message was rewritten or inserted by compaction.
 */
export function estimateContext(messages: AgentMessage[]): number {
	let newest = Number.NEGATIVE_INFINITY;
	let anchor = -1;
	let base = 0;
	messages.forEach((m: any, i) => {
		if (m.role === "assistant" && m.usage && m.stopReason !== "error" && m.stopReason !== "aborted" && m.timestamp >= newest) {
			const total = m.usage.input + m.usage.cacheRead + m.usage.cacheWrite + m.usage.output;
			if (total > 0) {
				anchor = i;
				base = total;
			}
		}
		newest = Math.max(newest, m.timestamp ?? 0);
	});
	if (anchor < 0) return messages.reduce((n, x) => n + estimateMessage(x), 0);
	return base + messages.slice(anchor + 1).reduce((n, x) => n + estimateMessage(x), 0);
}

function roughTotal(messages: AgentMessage[]): number {
	return messages.reduce((n, x) => n + estimateMessage(x), 0);
}

function pruneToolResults(messages: AgentMessage[], keepFrom: number): { messages: AgentMessage[]; pruned: number } {
	let pruned = 0;
	const now = Date.now();
	const out = messages.map((m: any, i) => {
		if (i < keepFrom && m.role === "toolResult" && messageText(m).length > 200) {
			pruned++;
			// The new timestamp is load-bearing: without it pi-ai keeps anchoring on the now-stale usage
			// of the next assistant message and clamps max_tokens down to 1 (found by T9c).
			return { ...m, content: [{ type: "text", text: PRUNED }], timestamp: now };
		}
		return m;
	});
	return { messages: out, pruned };
}

function findCut(messages: AgentMessage[], window: number): number {
	const budget = window * KEEP_RECENT_RATIO;
	let tokens = 0;
	let cut = messages.length;
	for (let i = messages.length - 1; i >= 1; i--) {
		tokens += estimateMessage(messages[i]);
		if (tokens > budget) break;
		if ((messages[i] as any).role !== "toolResult") cut = i;
	}
	if (cut < messages.length) return cut;
	// A single huge tail: still keep the last boundary that is not a tool result.
	for (let i = messages.length - 1; i >= 1; i--) if ((messages[i] as any).role !== "toolResult") return i;
	return messages.length;
}

/** The summary request must itself fit the window, so long messages lose their middle. */
function serialize(messages: AgentMessage[], window: number): string {
	const perMessage = Math.max(500, Math.floor(window * 0.2));
	const lines = messages.map((m: any) => {
		const t = messageText(m);
		if (t.length <= perMessage) return `[${m.role}] ${t}`;
		const half = Math.floor(perMessage / 2);
		return `[${m.role}] ${t.slice(0, half)}\n...[${t.length - perMessage} chars omitted]...\n${t.slice(-half)}`;
	});
	const all = lines.join("\n\n");
	const total = Math.floor(window * 0.6);
	if (estimateText(all) <= total) return all;
	return `${all.slice(0, Math.floor(total / 2))}\n...[omitted]...\n${all.slice(-Math.floor(total / 2))}`;
}

export interface CompactionResult {
	messages: AgentMessage[];
	summarized: boolean;
	prunedResults: number;
	before: number;
	after: number;
}

export async function compact(
	all: AgentMessage[],
	cfg: HarnessConfig,
	signal: AbortSignal | undefined,
	force: boolean,
): Promise<CompactionResult | undefined> {
	const window = cfg.model.contextWindow;
	const before = estimateContext(all);
	// pi-ai silently clamps max_tokens to window - estimate - 4096, floor 1 (simple-options.js), and a
	// clamped reply just ends with finish_reason=length. Compact before that point. Ratio > 1 turns
	// proactive compaction off (kit T9b).
	const threshold = cfg.compactRatio > 1 ? Number.POSITIVE_INFINITY : Math.min(window * cfg.compactRatio, window - CLAMP_RESERVE);
	if (!force && before <= threshold) return undefined;

	const hasSystem = (all[0] as any)?.role === "system";
	const system = hasSystem ? [all[0]] : [];
	const body = hasSystem ? all.slice(1) : all;

	// 1. prune tool results outside the recent suffix
	const pruneCut = findCut(body, window);
	const { messages: pruned, pruned: prunedResults } = pruneToolResults(body, pruneCut);
	const prunedTotal = roughTotal(pruned);
	if (!force && prunedResults > 0 && prunedTotal <= threshold * 0.8) {
		return { messages: [...system, ...pruned], summarized: false, prunedResults, before, after: prunedTotal };
	}

	// 2. summarize the prefix
	const cut = findCut(pruned, window);
	if (cut <= 0) return undefined;
	const old = pruned.slice(0, cut);
	const kept = pruned.slice(cut);
	const reply = await (cfg.models as any).completeSimple(
		cfg.auxModel ?? cfg.model,
		{
			systemPrompt: SYSTEM,
			messages: [{ role: "user", content: [{ type: "text", text: `${TEMPLATE}${serialize(old, window)}\n</conversation>` }], timestamp: Date.now() }],
		},
		{ signal },
	);
	if (reply.stopReason === "error" || reply.stopReason === "aborted") {
		throw new Error(`compaction summary failed: ${reply.errorMessage ?? reply.stopReason}`);
	}
	const summary = reply.content.filter((b: any) => b.type === "text").map((b: any) => b.text).join("");
	if (!summary.trim()) throw new Error("compaction summary came back empty");
	const summaryMsg = { role: "user", content: [{ type: "text", text: SUMMARY_PREFIX + summary }], timestamp: Date.now() } as AgentMessage;
	const out = [...system, summaryMsg, ...kept];
	return { messages: out, summarized: true, prunedResults, before, after: roughTotal(out) };
}
